export function normalizeMistlineIconName(raw?: string): string | undefined {
  if (!raw || typeof raw !== "string") return undefined;
  const key = raw
    .trim()
    .toLowerCase()
    .replace(/[\s_]+/g, "-")
    .replace(/[^a-z0-9-]/g, "");
  if (!key) return undefined;
  if (MISTLINE_ICONS[key]) return key;
  const aliased = ICON_ALIASES[key] || ICON_ALIASES[key.replace(/-/g, "_")];
  if (aliased && MISTLINE_ICONS[aliased]) return aliased;
  return undefined;
}

